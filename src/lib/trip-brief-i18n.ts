/** Day-narrative templates. `{day}`, `{totalDays}`, `{distanceLabel}`,
 *  `{gain}`, `{loss}`, and `{poiSentence}` are substituted by `formatDayNarrative`. */
const DAY_NARRATIVE_TEMPLATES = {
	en: 'Day {day} of {totalDays}: {distanceLabel}, +{gain} m / -{loss} m. {poiSentence}',
	hr: '{day}. dan od {totalDays}: {distanceLabel}, +{gain} m / -{loss} m. {poiSentence}',
	de: 'Tag {day} von {totalDays}: {distanceLabel}, +{gain} m / -{loss} m. {poiSentence}',
	it: 'Giorno {day} di {totalDays}: {distanceLabel}, +{gain} m / -{loss} m. {poiSentence}',
} as const;

/** Trailing sentence appended to the day narrative depending on whether the
 *  stage has at least one POI. */
const DAY_POI_SENTENCE = {
	en: { withPois: '{poiCount} places along the way.', empty: 'No notable places on this stage.' },
	hr: { withPois: '{poiCount} mjesta uz put.', empty: 'Nema posebnih mjesta uz ovu etapu.' },
	de: { withPois: '{poiCount} Orte am Weg.', empty: 'Keine besonderen Orte auf dieser Etappe.' },
	it: { withPois: '{poiCount} luoghi lungo il percorso.', empty: 'Nessun luogo notabile in questa tappa.' },
} as const;

/** Overview-narrative templates. `{totalDistanceLabel}`, `{dayCount}`,
 *  `{direction}`, and `{etaLabel}` are substituted by `formatOverviewNarrative`. */
const OVERVIEW_NARRATIVE_TEMPLATES = {
	en: 'The plan covers {totalDistanceLabel} across {dayCount} days {direction}. Estimated walking time: {etaLabel}.',
	hr: 'Plan obuhvaća {totalDistanceLabel} u {dayCount} dana {direction}. Procijenjeno vrijeme hodanja: {etaLabel}.',
	de: 'Der Plan umfasst {totalDistanceLabel} in {dayCount} Tagen {direction}. Geschätzte Gehzeit: {etaLabel}.',
	it: 'Il piano copre {totalDistanceLabel} in {dayCount} giorni {direction}. Tempo di cammino stimato: {etaLabel}.',
} as const;

/** Render the per-day narrative line for the trip brief. */
export function formatDayNarrative(args: {
	day: number;
	totalDays: number;
	distanceLabel: string;
	gainM: number;
	lossM: number;
	poiCount: number;
	locale: TripBriefLocale;
}): string {
	const { day, totalDays, distanceLabel, gainM, lossM, poiCount, locale } = args;
	const poiSentence =
		poiCount > 0
			? DAY_POI_SENTENCE[locale].withPois.replace('{poiCount}', String(poiCount))
			: DAY_POI_SENTENCE[locale].empty;
	return DAY_NARRATIVE_TEMPLATES[locale]
		.replace('{day}', String(day))
		.replace('{totalDays}', String(totalDays))
		.replace('{distanceLabel}', distanceLabel)
		.replace('{gain}', String(Math.round(gainM)))
		.replace('{loss}', String(Math.round(lossM)))
		.replace('{poiSentence}', poiSentence);
}

/** Render the trip-level overview narrative for the cover page. */
export function formatOverviewNarrative(args: {
	totalDistanceLabel: string;
	dayCount: number;
	direction: TrailDirection;
	locale: TripBriefLocale;
	etaLabel: string;
}): string {
	const { totalDistanceLabel, dayCount, direction, locale, etaLabel } = args;
	return OVERVIEW_NARRATIVE_TEMPLATES[locale]
		.replace('{totalDistanceLabel}', totalDistanceLabel)
		.replace('{dayCount}', String(dayCount))
		.replace('{direction}', NARRATIVE_DIRECTION[locale][direction])
		.replace('{etaLabel}', etaLabel);
}

