/** Day header string (e.g. "Day 1 - km 0 to 25") shared across PDF and DOCX. */
export function dayHeader(day: TripBriefDay, l: TripBriefLocale, units: TripBrief['meta']['units']): string {
	const k0 = Math.round(day.directionStartKm);
	const k1 = Math.round(day.directionEndKm);
	const unit = units === 'imperial' ? 'mi' : 'km';
	const w = {
		en: `Day ${day.index + 1} - ${unit} ${k0} to ${k1}`,
		hr: `${day.index + 1}. dan - ${unit} ${k0} do ${k1}`,
		de: `Tag ${day.index + 1} - ${unit} ${k0} bis ${k1}`,
		it: `Giorno ${day.index + 1} - ${unit} ${k0} a ${k1}`,
	};
	return w[l];
}

/** Format a distance value for display in trip-brief documents. */
export function formatKmRound(km: number, units: TripBrief['meta']['units']): string {
	if (units === 'imperial') return `${(km * 0.621371).toFixed(1)} mi`;
	return `${km.toFixed(1)} km`;
}

